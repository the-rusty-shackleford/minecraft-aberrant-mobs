package com.chunkworks.aberrantmobs.domain;

/** One corner of a face: an index into the mesh's positions and one into its uvs. */
public record Corner(int position, int uv) {
    public Corner {
        if (position < 0 || uv < 0) {
            throw new IllegalArgumentException("indices are non-negative: " + position + "/" + uv);
        }
    }
}
