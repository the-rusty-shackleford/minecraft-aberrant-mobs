package com.chunkworks.aberrantmobs.mixin;

import com.chunkworks.aberrantmobs.wallwalk.WallWalk;
import net.minecraft.world.entity.Entity;
import net.minecraft.world.level.Explosion;
import net.minecraft.world.phys.Vec3;
import org.spongepowered.asm.mixin.Mixin;
import org.spongepowered.asm.mixin.injection.At;
import org.spongepowered.asm.mixin.injection.Redirect;

/** Keeps the explosion's public/packet impulse in world axes; only velocity storage is local. */
@Mixin(Explosion.class)
public abstract class ExplosionMixin {
    @Redirect(method = "explode", at = @At(value = "INVOKE", target = "Lnet/minecraft/world/entity/Entity;setDeltaMovement(Lnet/minecraft/world/phys/Vec3;)V"))
    private void aberrantmobs$impulseInFrame(Entity entity, Vec3 sum) {
        if (!WallWalk.bent(entity)) {
            entity.setDeltaMovement(sum);
            return;
        }
        WallWalk.addWorldImpulse(entity, sum.subtract(entity.getDeltaMovement()));
    }
}
